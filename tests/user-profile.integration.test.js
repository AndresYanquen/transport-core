const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');

test('profile and identity PostgreSQL integration', { skip: process.env.RUN_PROFILE_DB_TESTS !== '1' }, async (t) => {
  const schema = `profile_test_${crypto.randomBytes(8).toString('hex')}`;
  process.env.DB_SEARCH_PATH = `${schema},public,extensions`;
  const config = require('../knexfile').test;
  const knex = require('knex')({ ...config, searchPath: [schema, 'public', 'extensions'], migrations: { ...config.migrations, schemaName: schema } });
  const { pool } = require('../src/config/database');
  t.after(async () => { await pool.end(); await knex.raw(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); await knex.destroy(); });
  await knex.raw(`CREATE SCHEMA "${schema}"`);
  await knex.migrate.latest();
  const Auth = require('../src/modules/auth/models/auth.model');
  const Profiles = require('../src/modules/users/services/user.service');
  const Identity = require('../src/modules/auth/services/identity-change.service');
  const Email = require('../src/modules/email/services/email.service');
  const Phone = require('../src/modules/auth/services/phone-auth.service');
  const Sms = require('../src/modules/auth/services/otp-sms.service');
  const { env } = require('../src/config');
  env.redis.url = "";
  const bcrypt = require('bcryptjs');
  const admin = { id: crypto.randomUUID(), role: 'admin' };
  const client = { id: crypto.randomUUID(), role: 'client' };
  const driver = { id: crypto.randomUUID(), role: 'driver' };
  const password = 'initial-password';
  const passwordHash = await bcrypt.hash(password, 4);
  for (const user of [admin, client, driver]) await knex('users').insert({ id: user.id, role: user.role, email: `${user.role}@example.test`, email_verified: true, first_name: 'Original', last_name: 'Preserved', password_hash: passwordHash });
  await knex('clients').insert({ user_id: client.id, default_payment_method: 'cash' });
  await knex('drivers').insert({ user_id: driver.id, license_number: 'LIC123', vehicle_make: 'Make', vehicle_model: 'Model', vehicle_plate: 'ABC123', approval_status: 'approved', status: 'online', documents: { insurance: 'https://example.test/old', legacy: 'preserved' } });
  const asUser = async (u) => Auth.toPublicUser(await Auth.findById(u.id));
  t.mock.method(require('../src/modules/drivers/services/driver-presence-cache.service'), 'removeRecentPresenceBestEffort', () => {});
  let deliveredCode;
  t.mock.method(Email, 'isMailConfigured', () => true);
  t.mock.method(Email, 'sendIdentityCodeEmail', async ({ code }) => { deliveredCode = code; });

  await t.test('partial updates, geography clearing, operator restrictions and audit', async () => {
    const result = await Profiles.updateUser(client, client.id, { firstName: 'New', clientProfile: { homeLocation: { lat: 4.7, lng: -74 } } });
    assert.equal(result.user.lastName, 'Preserved');
    assert.equal(result.user.clientProfile.defaultPaymentMethod, 'cash');
    assert.deepEqual(result.user.clientProfile.homeLocation.coordinates, [-74, 4.7]);
    assert.equal((await Profiles.updateUser(client, client.id, { clientProfile: { homeLocation: null } })).user.clientProfile.homeLocation, null);
    await assert.rejects(Profiles.updateUser(client, driver.id, { firstName: 'Bad' }), { status: 403 });
    await assert.rejects(Profiles.getUser({ role: 'operator' }, driver.id), { status: 404 });
    assert.equal((await Profiles.getUser({ role: 'operator' }, client.id)).user.id, client.id);
    const audit = await knex('user_change_audit').where({ user_id: client.id }).first();
    assert.deepEqual(audit.fields, ['firstName', 'clientProfile.homeLocation']);
  });
  await t.test('driver changes preserve documents, reset approval only when changed and prevent edits during rides', async () => {
    assert.equal((await Profiles.updateUser(driver, driver.id, { driverProfile: { vehicleColor: 'blue' } })).approvalRequired, false);
    assert.equal((await Profiles.updateUser(driver, driver.id, { driverProfile: { vehiclePlate: 'ABC123' } })).approvalRequired, false);
    const result = await Profiles.updateUser(driver, driver.id, { driverProfile: { vehiclePlate: 'NEW123', documents: { insurance: null, licenseFront: 'https://example.test/license' } } });
    assert.equal(result.approvalRequired, true);
    assert.equal(result.user.driverProfile.approvalStatus, 'pending');
    assert.equal(result.user.driverProfile.status, 'offline');
    assert.deepEqual(result.user.driverProfile.documents, { legacy: 'preserved', licenseFront: 'https://example.test/license' });
    const rideId = crypto.randomUUID();
    await knex('rides').insert({ id: rideId, client_id: client.id, driver_id: driver.id, status: 'in_progress', pickup_point: knex.raw("ST_GeogFromText('SRID=4326;POINT(-74 4.7)')") });
    await assert.rejects(Profiles.updateUser(driver, driver.id, { firstName: 'Rollback', driverProfile: { licenseNumber: 'NEW-LIC' } }), { status: 409 });
    assert.equal((await Auth.findById(driver.id)).first_name, 'Original');
    await knex('rides').where({ id: rideId }).update({ status: 'completed' });
  });
  await t.test('identity proof is required; email replacement is verified and one-time', async () => {
    await assert.rejects(Identity.requestEmailChange(client, { email: 'new@example.test' }, {}), { status: 401 });
    const challenge = await Identity.requestEmailChange(client, { email: 'new@example.test', currentPassword: password }, {});
    assert.equal((await Auth.findById(client.id)).email, 'client@example.test');
    const code = deliveredCode;
    await assert.rejects(Identity.verifyEmailChange(client, { challengeId: challenge.challengeId, code: code === '000000' ? '111111' : '000000' }), { status: 401 });
    assert.equal((await knex('auth_identity_challenges').where({ id: challenge.challengeId }).first()).attempts, 1);
    const result = await Identity.verifyEmailChange(client, { challengeId: challenge.challengeId, code });
    assert.equal(result.user.email, 'new@example.test');
    assert.equal(result.requiresLogin, true);
    assert.equal((await Auth.findById(client.id)).security_version, 1);
    await assert.rejects(Identity.verifyEmailChange(client, { challengeId: challenge.challengeId, code }), { status: 401 });
  });
  await t.test('expired email challenges and provider failures leave current identity intact', async () => {
    const challenge = await Identity.requestEmailChange(client, { email: 'expired@example.test', currentPassword: password }, {});
    await knex('auth_identity_challenges').where({ id: challenge.challengeId }).update({ expires_at: new Date(Date.now() - 1000) });
    await assert.rejects(Identity.verifyEmailChange(client, { challengeId: challenge.challengeId, code: deliveredCode }), { status: 401 });
    await assert.rejects(Identity.verifyEmailChange(client, { challengeId: '-'.repeat(36), code: '123456' }), { status: 400 });
    const before = await knex('auth_identity_challenges').count('* as total').first();
    const failing = t.mock.method(Email, 'sendIdentityCodeEmail', async () => { throw new Error('provider failure'); });
    await assert.rejects(Identity.requestEmailChange(client, { email: 'failed@example.test', currentPassword: password }, {}), { status: 503 });
    failing.mock.restore();
    assert.equal((await knex('auth_identity_challenges').count('* as total').first()).total, before.total);
    assert.equal((await Auth.findById(client.id)).email, 'new@example.test');
  });
  await t.test('verified email proof adds a password to an account and cannot be replayed', async () => {
    await knex('users').where({ id: client.id }).update({ password_hash: null });
    const challenge = await Identity.requestEmailProof(client);
    const proof = await Identity.verifyEmailProof(client, { challengeId: challenge.challengeId, code: deliveredCode });
    await Identity.changePassword(client, { password: 'new-password', reauthToken: proof.reauthToken }, {});
    assert.ok(await bcrypt.compare('new-password', (await Auth.findById(client.id)).password_hash));
    await assert.rejects(Identity.changePassword(client, { password: 'another-password', reauthToken: proof.reauthToken }, {}), { status: 401 });
    const audit = await knex('user_change_audit').where({ action: 'password_changed' }).first();
    assert.deepEqual(audit.fields, ['password']);
    assert.ok(!JSON.stringify(audit).includes('new-password'));
  });
  await t.test('changing a verified phone binds OTP to the original credentials and replaces sessions', async () => {
    Object.assign(env.phoneAuth, { enabled: true, smsProvider: 'mock', rolloutPercent: 100, allowedNumbers: [], hashSecret: crypto.randomBytes(32).toString('hex') });
    env.inalambria.apiKey = 'test_mock';
    await knex('users').where({ id: client.id }).update({ phone_number: '+573001112210', phone_verified: true });
    const deviceId = crypto.randomUUID();
    let user = await asUser(client);
    let credentialVersion = await Identity.authorizePhoneChange(user, { currentPassword: 'new-password' }, {});
    let challenge = await Phone.requestOtp({ phoneNumber: '+573001112211', deviceId, requestId: crypto.randomUUID() }, { linkUser: user, changePhone: true, credentialVersion });
    let code = Sms.takeMockOtp('+573001112211');
    await knex('users').where({ id: client.id }).increment('security_version', 1);
    await assert.rejects(Phone.verifyOtp({ challengeId: challenge.challengeId, code, deviceId }, { linkUser: user, changePhone: true }), { status: 401 });
    await knex('auth_phone_sms_requests').delete(); await knex('auth_phone_rate_limits').delete();
    user = await asUser(client);
    credentialVersion = await Identity.authorizePhoneChange(user, { currentPassword: 'new-password' }, {});
    challenge = await Phone.requestOtp({ phoneNumber: '+573001112212', deviceId, requestId: crypto.randomUUID() }, { linkUser: user, changePhone: true, credentialVersion });
    code = Sms.takeMockOtp('+573001112212');
    const result = await Phone.verifyOtp({ challengeId: challenge.challengeId, code, deviceId }, { linkUser: user, changePhone: true });
    assert.equal(result.user.phoneNumber, '+573001112212');
    assert.equal(result.user.phoneVerified, true);
    assert.ok(result.accessToken);
    const activeSession = await knex('auth_mobile_sessions').where({ user_id: client.id }).whereNull('revoked_at').first();
    const recentAuth = { payload: { sid: activeSession.id } };
    await Identity.authorizePhoneChange(result.user, {}, recentAuth);
    await knex('auth_mobile_sessions').where({ id: activeSession.id }).update({ created_at: new Date(Date.now() - 360000) });
    await assert.rejects(Identity.authorizePhoneChange(result.user, {}, recentAuth), { status: 401 });
    assert.equal((await knex('auth_mobile_sessions').where({ user_id: client.id }).whereNull('revoked_at')).length, 1);
  });
  await t.test('HTTP profile permissions and credential version revocation', async () => {
    const server = require('../src/app').listen(0, '127.0.0.1');
    await new Promise((resolve) => server.once('listening', resolve));
    try {
      const sign = require('../src/modules/auth/services/auth.service').signAccessToken;
      const url = `http://127.0.0.1:${server.address().port}`;
      const request = (path, token, method = 'GET', body) => fetch(url + path, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
      const token = sign(admin).accessToken;
      assert.equal((await request(`/api/admin/users/${client.id}`, token)).status, 200);
      assert.equal((await request(`/api/admin/users/${client.id}`, token, 'PATCH', { firstName: 'From HTTP' })).status, 200);
      assert.equal((await request('/api/admin/users/not-a-uuid', token)).status, 400);
      assert.equal((await request('/api/users/me', token)).status, 403);
      const stale = sign(client).accessToken;
      assert.equal((await request('/api/auth/me', stale)).status, 401);
      const op = { id: crypto.randomUUID(), role: 'operator' };
      await knex('users').insert({ id: op.id, role: 'operator' });
      const opToken = sign(op).accessToken;
      assert.equal((await request(`/api/admin/users/${driver.id}`, opToken)).status, 404);
      assert.equal((await request(`/api/admin/users/${client.id}`, opToken, 'PATCH', { firstName: 'Forbidden' })).status, 403);
    } finally { await new Promise((resolve) => server.close(resolve)); }
  });
  await t.test('administrative status changes are isolated and audited', async () => {
    await assert.rejects(Profiles.updateUser(admin, client.id, { status: 'suspended' }), { status: 400 });
    await assert.rejects(Profiles.updateStatus(client, driver.id, { status: 'suspended' }), { status: 403 });
    assert.equal((await Profiles.updateStatus(admin, client.id, { status: 'suspended' })).user.status, 'suspended');
    assert.equal((await knex('auth_mobile_sessions').where({ user_id: client.id }).whereNull('revoked_at')).length, 0);
  });
});
